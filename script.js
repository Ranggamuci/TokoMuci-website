// FILTER KATEGORI
// ======================================================

function setupFilterKategori() {

    const filterBtns =
        document.querySelectorAll(".filter-btn");


    filterBtns.forEach(btn => {

        btn.addEventListener("click", () => {


            // Reset semua tombol
            filterBtns.forEach(b => {

                b.classList.remove(
                    "active",
                    "bg-indigo-600",
                    "text-white",
                    "shadow-md",
                    "shadow-indigo-500/20"
                );


                b.classList.add(
                    "bg-slate-100",
                    "text-slate-700"
                );

            });


            // Aktifkan tombol
            btn.classList.add(
                "active",
                "bg-indigo-600",
                "text-white",
                "shadow-md",
                "shadow-indigo-500/20"
            );


            btn.classList.remove(
                "bg-slate-100",
                "text-slate-700"
            );


            // Ambil kategori
            currentCategory =
                btn.getAttribute("data-category");


            // Render ulang
            renderATK();

        });

    });

}


// ======================================================
// SEARCH
// ======================================================

function setupSearch() {

    const searchInput =
        document.getElementById("searchInput");

    const clearSearch =
        document.getElementById("clearSearch");

    if (!searchInput) return;

    searchInput.addEventListener(
        "input",
        event => {

            searchQuery =
                event.target.value.trim();

            if (searchQuery.length > 0) {
                if (clearSearch) {
                    clearSearch.classList.remove("hidden");
                }
            } else {
                if (clearSearch) {
                    clearSearch.classList.add("hidden");
                }
            }

            renderATK();
        }
    );

    // Tombol hapus pencarian
    if (clearSearch) {

        clearSearch.addEventListener(
            "click",
            () => {

                searchInput.value = "";
                searchQuery = "";

                clearSearch.classList.add("hidden");

                renderATK();

                searchInput.focus();
            }
        );
    }
}

// ======================================================
// INISIALISASI
// ======================================================

function initATK() {

    try {

        setupFilterKategori();

        setupSearch();

        renderATK();

        console.log(
            "Katalog ATK berhasil dimuat:",
            daftarATK.length,
            "produk"
        );

    } catch (error) {

        console.error(
            "Gagal memuat katalog ATK:",
            error
        );

    }

}


// ======================================================
// JALANKAN SCRIPT
// ======================================================

if (document.readyState === "loading") {

    document.addEventListener(
        "DOMContentLoaded",
        initATK
    );

} else {

    initATK();

}
